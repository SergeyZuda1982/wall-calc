/**
 * Борт (короб) между двумя уровнями многоуровневого потолка — узел из
 * рабочих альбомов КНАУФ, см. переписку 16.09.2026 (тема "П19").
 *
 * ─── Архитектура ────────────────────────────────────────────────────────────
 * Сами уровни (верхняя и нижняя плоскости) — это ОБЫЧНЫЕ существующие
 * сущности `Ceiling` с `ceilingSpec.type` = 'p112' | 'p113' (движок расчёта
 * не меняется вообще). Плоская отметка каждого уровня задаётся через уже
 * существующее поле `Ceiling.slope` со `SlopePlane.height1Mm === height2Mm`
 * (уклон = 0, просто смещённая по высоте плоскость) — отдельного поля
 * "высота уровня" заводить не пришлось.
 *
 * `CeilingBorder` (types/index.ts) — САМОСТОЯТЕЛЬНАЯ сущность-коннектор
 * между двумя уровнями: путь по плану (НЕ обязательно замкнутый — по
 * подтверждению пользователя 16.09.2026 бывает и кольцом по всему
 * периметру, и вдоль части стен "от края до края"), + параметры сечения
 * узла (опуск/полка) + тип узла (каталог ниже, сейчас один пункт).
 *
 * ─── Узел p112_p113_angle_connector, состав (16.09.2026, с реального
 * объекта пользователя, кинотеатр "Ростов", 6 ступеней +3.300…+4.500) ──────
 * Верх борта — профиль 27×28, крепится ЧЕРЕЗ обшивку (ГКЛ) верхнего уровня
 * В несущий профиль каркаса верхнего уровня (не напрямую в металл и не
 * просто в лист) — шаг крепления ~300мм (задан пользователем "на глаз",
 * не по официальной таблице КНАУФ — в отличие от stepA у calcP112Frame.ts).
 * Низ борта — угловое соединение вертикального отрезка профиля 60×27 с
 * несущим профилем 60×27 нижнего уровня. Так как нижний уровень — П112/П113
 * со своим шагом несущего профиля (stepC), пользователь подтвердил: шаг
 * угловых соединителей = тот же stepC (не отдельная величина).
 * На каждый угловой соединитель — 4×LN. На каждый вертикальный отрезок
 * профиля 60×27 (длиной = dropMm, один на каждый соединитель) — ~3×TN.
 * Обшивка борта — ОДИН лист ГКЛ (не два стыкуемых куска), фрезерованный
 * под 90° и проклеенный клей-пеной по линии фрезеровки — в расчёте v1
 * материал борта считается ПЛОЩАДЬЮ полосы (dropMm+shelfDepthMm) × длина
 * пути, раскрой на конкретные листы 1200×sheetLengthMm — по норме площади,
 * БЕЗ точной раскладки кусков (см. предупреждение в calcCeilingBorder.ts) —
 * это сознательное упрощение v1, как и было решено в переписке.
 *
 * ─── НЕ реализовано в v1 (задел на будущее, поля есть, расчёт — нет) ───────
 * Ниша под LED-подсветку (nicheDepthMm/nicheHeightMm/ledGapMm) и отделка
 * борта отличным от окраски материалом (СМЛ-панели, бамбук, штукатурка —
 * см. "Ведомость отделки потолков" в проекте пользователя, ТИП-2/ТИП-3) —
 * пользователь подтвердил, что это нужно "значительно позже". Скругление
 * борта (альтернатива фрезерованному прямому углу, см. "Скругление короба
 * потолка" R80 в PDF проекта) — тоже не реализовано, это альтернативный
 * jointType на будущее.
 */

/** Каталог типов узла борта. Пока один пункт — намеренно оставлено как
 *  union (не просто string), чтобы TypeScript не давал молча забыть добавить
 *  обработку нового варианта, когда он появится. */
export type CeilingBorderJointType = 'p112_p113_angle_connector'

